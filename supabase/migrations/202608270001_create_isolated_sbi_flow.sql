-- SBI is intentionally isolated from the existing BOB production tables.
-- This migration only creates new SBI-prefixed objects; it does not alter,
-- update, delete, or copy any existing BOB data.

create table if not exists public.sbi_executives (
  id uuid primary key default gen_random_uuid(),
  executive_code text not null unique check (executive_code ~ '^SBI[0-9]{3,}$'),
  full_name text not null,
  mobile text,
  area text,
  vehicle_type text,
  status text not null default 'pending',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.sbi_cases (
  id uuid primary key default gen_random_uuid(),
  sn integer,
  case_type text,
  alpha text,
  sol_id text,
  account_number text not null unique,
  account_name text not null,
  customer_id text,
  sanction_limit numeric not null default 0,
  sanction_date date,
  scheme_code text,
  rev_seg text,
  customer_balance numeric not null default 0,
  balance_inr numeric not null default 0,
  ecgc_receivable numeric not null default 0,
  asset_class text,
  npa_date date,
  two text,
  fraud text,
  total_provision numeric not null default 0,
  branch text,
  address text,
  mobile_number text,
  village text,
  bank_name text not null default 'State Bank of India (SBI)',
  status text not null default 'pending',
  assigned_executive_id uuid references public.sbi_executives(id) on delete set null,
  assigned_executive text,
  executive_code text,
  remarks text,
  source_file text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.sbi_payments (
  id uuid primary key default gen_random_uuid(),
  case_id uuid not null references public.sbi_cases(id) on delete restrict,
  executive_id uuid references public.sbi_executives(id) on delete set null,
  amount numeric not null check (amount > 0),
  payment_mode text,
  reference_number text,
  receipt_number text,
  remarks text,
  payment_date date not null default current_date,
  created_at timestamptz not null default now()
);

create table if not exists public.sbi_field_visits (
  id uuid primary key default gen_random_uuid(),
  case_id uuid not null references public.sbi_cases(id) on delete restrict,
  executive_id uuid references public.sbi_executives(id) on delete set null,
  photo_path text,
  latitude double precision,
  longitude double precision,
  outcome text,
  remarks text,
  next_follow_up date,
  captured_at timestamptz not null default now()
);

create table if not exists public.sbi_followups (
  id uuid primary key default gen_random_uuid(),
  case_id uuid not null references public.sbi_cases(id) on delete cascade,
  executive_id uuid references public.sbi_executives(id) on delete set null,
  followup_date date not null,
  status text not null default 'pending',
  remarks text,
  created_at timestamptz not null default now()
);

create table if not exists public.sbi_gps_locations (
  id bigint generated by default as identity primary key,
  executive_id uuid not null references public.sbi_executives(id) on delete cascade,
  latitude double precision not null,
  longitude double precision not null,
  accuracy double precision,
  recorded_at timestamptz not null default now()
);

create index if not exists sbi_cases_executive_idx on public.sbi_cases(assigned_executive_id);
create index if not exists sbi_payments_case_idx on public.sbi_payments(case_id);
create index if not exists sbi_visits_case_idx on public.sbi_field_visits(case_id);
create index if not exists sbi_followups_case_idx on public.sbi_followups(case_id);
create index if not exists sbi_gps_executive_time_idx on public.sbi_gps_locations(executive_id, recorded_at desc);

