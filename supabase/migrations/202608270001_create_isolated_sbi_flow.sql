create or replace function public.sbi_register_executive(
  p_full_name text, p_mobile text, p_area text, p_vehicle_type text
) returns setof public.sbi_executives
language plpgsql security definer set search_path = public as $$
declare
  next_number integer;
  created public.sbi_executives;
begin
  if nullif(trim(p_full_name), '') is null or p_mobile !~ '^[0-9]{10,15}$'
     or nullif(trim(p_area), '') is null then
    raise exception 'Name, valid mobile aur area required hai';
  end if;
  if exists (select 1 from public.sbi_executives where mobile = p_mobile) then
    raise exception 'Is mobile number se registration pehle se maujood hai';
  end if;
  perform pg_advisory_xact_lock(hashtext('sbi_executive_code'));
  select coalesce(max(substring(executive_code from '[0-9]+$')::integer), 0) + 1
    into next_number from public.sbi_executives;
  insert into public.sbi_executives(executive_code, full_name, mobile, area, vehicle_type)
  values ('SBI' || lpad(next_number::text, 3, '0'), trim(p_full_name), p_mobile, trim(p_area), p_vehicle_type)
  returning * into created;
  return next created;
end $$;

create or replace function public.sbi_mobile_find_executive(
  p_id text default null, p_code text default null, p_mobile text default null
) returns setof public.sbi_executives
language sql security definer stable set search_path = public as $$
  select e.* from public.sbi_executives e
  where (p_id is not null and e.id::text = p_id)
     or (p_code is not null and p_mobile is not null
         and lower(e.executive_code) = lower(trim(p_code)) and e.mobile = p_mobile)
  limit 1
$$;

create or replace function public.sbi_mobile_executive_cases(
  p_executive_id text, p_executive_code text, p_mobile text
) returns setof public.sbi_cases
language sql security definer stable set search_path = public as $$
  select c.* from public.sbi_cases c
  join public.sbi_executives e on e.id::text = p_executive_id
  where e.status in ('active','approved','online')
    and lower(e.executive_code) = lower(trim(p_executive_code)) and e.mobile = p_mobile
    and (c.assigned_executive_id = e.id or lower(c.executive_code) = lower(e.executive_code))
  order by c.created_at desc
$$;

create or replace function public.sbi_mobile_update_case_status(
  p_case_id text, p_executive_id text, p_executive_code text, p_mobile text, p_status text
) returns boolean language plpgsql security definer set search_path = public as $$
begin
  update public.sbi_cases c set status = p_status, updated_at = now()
  from public.sbi_executives e
  where c.id::text = p_case_id and e.id::text = p_executive_id
    and lower(e.executive_code) = lower(trim(p_executive_code)) and e.mobile = p_mobile
    and (c.assigned_executive_id = e.id or lower(c.executive_code) = lower(e.executive_code));
  return found;
end $$;

create or replace function public.sbi_mobile_executive_payments(
  p_executive_id text, p_executive_code text, p_mobile text
) returns setof public.sbi_payments
language sql security definer stable set search_path = public as $$
  select p.* from public.sbi_payments p
  join public.sbi_executives e on e.id = p.executive_id
  where e.id::text = p_executive_id
    and lower(e.executive_code) = lower(trim(p_executive_code)) and e.mobile = p_mobile
  order by p.created_at desc
$$;

create or replace function public.sbi_mobile_record_payment(
  p_case_id text, p_executive_id text, p_executive_code text, p_mobile text,
  p_amount numeric, p_payment_mode text, p_reference_number text,
  p_receipt_number text, p_remarks text, p_payment_date date
) returns uuid language plpgsql security definer set search_path = public as $$
declare created_id uuid;
begin
  if p_amount <= 0 then raise exception 'Payment amount invalid hai'; end if;
  insert into public.sbi_payments(case_id, executive_id, amount, payment_mode,
    reference_number, receipt_number, remarks, payment_date)
  select c.id, e.id, p_amount, p_payment_mode, p_reference_number,
    p_receipt_number, p_remarks, p_payment_date
  from public.sbi_cases c join public.sbi_executives e on e.id::text = p_executive_id
  where c.id::text = p_case_id and lower(e.executive_code) = lower(trim(p_executive_code))
    and e.mobile = p_mobile and (c.assigned_executive_id = e.id or lower(c.executive_code) = lower(e.executive_code))
  returning id into created_id;
  if created_id is null then raise exception 'Case SBI executive ko assigned nahi hai'; end if;
  return created_id;
end $$;

create or replace function public.sbi_mobile_save_gps_location(
  p_executive_id text, p_executive_code text, p_mobile text, p_latitude double precision,
  p_longitude double precision, p_accuracy double precision, p_recorded_at timestamptz
) returns bigint language plpgsql security definer set search_path = public as $$
declare created_id bigint;
begin
  insert into public.sbi_gps_locations(executive_id, latitude, longitude, accuracy, recorded_at)
  select e.id, p_latitude, p_longitude, p_accuracy, p_recorded_at from public.sbi_executives e
  where e.id::text = p_executive_id and lower(e.executive_code) = lower(trim(p_executive_code)) and e.mobile = p_mobile
  returning id into created_id;
  return created_id;
end $$;

create or replace function public.sbi_mobile_record_detailed_visit(
  p_case_id text, p_executive_id text, p_executive_code text, p_mobile text,
  p_photo_path text, p_latitude double precision, p_longitude double precision,
  p_outcome text, p_remarks text, p_next_follow_up date
) returns uuid language plpgsql security definer set search_path = public as $$
declare created_id uuid;
begin
  insert into public.sbi_field_visits(case_id, executive_id, photo_path, latitude,
    longitude, outcome, remarks, next_follow_up)
  select c.id, e.id, p_photo_path, p_latitude, p_longitude, p_outcome, p_remarks, p_next_follow_up
  from public.sbi_cases c join public.sbi_executives e on e.id::text = p_executive_id
  where c.id::text = p_case_id and lower(e.executive_code) = lower(trim(p_executive_code))
    and e.mobile = p_mobile and (c.assigned_executive_id = e.id or lower(c.executive_code) = lower(e.executive_code))
  returning id into created_id;
  if created_id is null then raise exception 'Case SBI executive ko assigned nahi hai'; end if;
  update public.sbi_cases set status = 'Visited', updated_at = now() where id::text = p_case_id;
  return created_id;
end $$;

